const fs = require('fs');
const path = require('path');

// Grab API_URL from environment or use the production Render backend
const apiUrl = process.env.API_URL || 'https://landville-backend-web-api.onrender.com/api/v1';

const envConfigFile = `// Auto-generated by set-env.js
export const environment = {
  production: true,
  profileUrl: '${apiUrl}/auth/profile/',
  api_url: '${apiUrl}'
};
`;

const devConfigFile = `// Auto-generated by set-env.js (development / fallback)
export const environment = {
  production: false,
  profileUrl: '${apiUrl}/auth/profile/',
  api_url: '${apiUrl}'
};
`;

const targets = [
  { path: path.join(__dirname, 'src', 'environments', 'environment.prod.ts'), content: envConfigFile },
  { path: path.join(__dirname, 'src', 'environments', 'environment.ts'), content: process.env.NODE_ENV === 'production' ? envConfigFile : devConfigFile },
];

for (const target of targets) {
  try {
    fs.writeFileSync(target.path, target.content, 'utf8');
    console.log(`Updated ${path.relative(__dirname, target.path)} with API_URL: ${apiUrl}`);
  } catch (err) {
    console.error(`Error updating ${target.path}:`, err);
    process.exit(1);
  }
}
